# Exercise 3: Check Python keywords

import keyword

print("Is 'while' a keyword?", keyword.iskeyword("while"))
print("Is 'score' a keyword?", keyword.iskeyword("score"))

# Sample Output:
# Is 'while' a keyword? True
# Is 'score' a keyword? False


